def fetch_universe() -> pd.DataFrame:
    logger.info("📡 Fetching NSE stocks and forensic accounting data from TradingView...")

    fields = [
        "name", "sector", "close", "average_volume_30d_calc",
        "market_cap_basic", "return_on_equity_fy", "operating_margin", 
        "debt_to_equity_fq", "return_on_assets_fq", "return_on_invested_capital_fq", "earnings_per_share_basic_ttm",
        "gross_profit_yoy_growth_ttm", "gross_profit_qoq_growth_fq",
        "earnings_per_share_diluted_yoy_growth_ttm", "earnings_per_share_diluted_qoq_growth_fq",
        "total_revenue_yoy_growth_ttm", "total_revenue_qoq_growth_fq",
        "net_income_yoy_growth_ttm", "net_income_qoq_growth_fq",
        "price_earnings_ttm", 
        "price_book_ratio",
        "total_revenue_5y_growth",
        "earnings_per_share_basic_5y_growth",
        "free_cash_flow_margin_ttm",
        "dividend_yield_recent",
        "float_shares_outstanding",                      # [VERSION: DAILY_BUILDER_PATCH_v1.8] Added for Promoter MCAP calculation
        "total_shares_outstanding_fundamental"           # [VERSION: DAILY_BUILDER_PATCH_v1.8] Added for Promoter MCAP calculation
    ]

    q = (
        Query()
        .set_markets("india")
        .select(*fields)
        .where(
            # [VERSION: DAILY_BUILDER_PATCH_v1.8] Query both exchanges to fetch BSE-exclusive tickers
            col("exchange").isin(["NSE", "BSE"]),
            col("close")                        >= MIN_PRICE,
            col("market_cap_basic")             >= MIN_MARKET_CAP,
            col("average_volume_30d_calc")      >= 50000,
            # [VERSION: DAILY_BUILDER_PATCH_v1.6] Removed col("operating_margin") >= 0
            # Rationale: Python junk gates (opm < 0, roa < 0.8) handle filtering.
            # Keeps financial names (banks/NBFCs) that may have null OPM in the universe.
        )
        .limit(5000)
    )

    try:
        logger.warning(
            "UNIVERSE BUILD: Survivorship bias present. "
            "Delisted/suspended tickers excluded. Backtest results will be overstated."
        )
        total, df = q.get_scanner_data()
        
        # [VERSION: DAILY_BUILDER_PATCH_v1.8] Deduplicate cross-listed stocks, keeping NSE representation when available.
        # Since 'N' > 'B', sorting descending by 'ticker' puts 'NSE:' above 'BSE:'
        if not df.empty:
            df = df.sort_values(by="ticker", ascending=False)
            df = df.drop_duplicates(subset=["name"], keep="first")
            
        from data_fetch_status import mark_success
        mark_success('tradingview')
        logger.info(f"✅ Universe fetched and deduplicated: {len(df)} unique stocks (from {total} records)")
        return df
    except Exception as e:
        from data_fetch_status import mark_failure
        mark_failure('tradingview', e)
        logger.exception(f"❌ TradingView fetch failed")
        return pd.DataFrame()

