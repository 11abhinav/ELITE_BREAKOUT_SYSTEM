def _classify_nonfin(row: pd.Series, symbol: str) -> dict:
    def fv(c): return _fval(row, c)
    def skip(r): 
        log_exclusion(symbol, r)
        return None

    try:
        from fundamentals_cache import get_fundamentals
        fund_data = get_fundamentals(symbol)
    except Exception:
        fund_data = {}

