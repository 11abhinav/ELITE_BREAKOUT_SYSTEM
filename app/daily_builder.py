def _classify_fin(row: pd.Series, symbol: str) -> dict:
    def fv(c): return _fval(row, c)
    def skip(r): 
        log_exclusion(symbol, r)
        return None

    try:
        from fundamentals_cache import get_fundamentals
        fund_data = get_fundamentals(symbol)
    except Exception:
        fund_data = {}

    insider_hold = fund_data.get("insider_hold")
    forensic_flags = fund_data.get("forensic_flags", 0)

    close_price = fv("close")
    avg_volume  = fv("average_volume_30d_calc")
    market_cap  = fv("market_cap_basic")
    roe         = fv("return_on_equity_fy")
    roa         = fv("return_on_assets_fq")

    _raw_de      = fv("debt_to_equity_fq")
    debt_equity  = _raw_de if _raw_de is not None else 0.0
    debt_missing = _raw_de is None

    yoy_rev    = fv("total_revenue_yoy_growth_ttm")
    qoq_rev    = fv("total_revenue_qoq_growth_fq")
    yoy_profit = fv("net_income_yoy_growth_ttm")
    qoq_profit = fv("net_income_qoq_growth_fq")

    pe          = fv("price_earnings_ttm")
    pb          = fv("price_book_ratio")
    
    # Valuation fallbacks for TradingView missing data
    if pe is None: pe = fund_data.get("pe_fallback")
    if pb is None: pb = fund_data.get("pb_fallback")
    
    rev_5y      = fv("total_revenue_5y_growth")
    eps_5y      = fv("earnings_per_share_basic_5y_growth")
    div_yield   = fv("dividend_yield_recent")
    fcf_margin  = fv("free_cash_flow_margin_ttm")
    _raw_roce   = fv("return_on_invested_capital_fq")
    # [VERSION: DAILY_BUILDER_PATCH_v1.7] Preserve None for missing ROCE
    roce        = _raw_roce

    # [VERSION: DAILY_BUILDER_PATCH_v1.8] Removed total_revenue_qoq_growth_fq and net_income_qoq_growth_fq
    # from the hard-exclusion checklist to allow stocks with temporary database lags to pass.
    missing = [
        name for name, val in [
            ("close", close_price), ("average_volume_30d_calc", avg_volume),
            ("market_cap_basic", market_cap), ("return_on_equity_fy", roe),
            ("return_on_assets_fq", roa), ("total_revenue_yoy_growth_ttm", yoy_rev),
            ("net_income_yoy_growth_ttm", yoy_profit),
        ] if val is None
    ]
    if missing:
        return skip(f"Missing data (financial path): {', '.join(missing)}")

    if roa < MIN_ROA_FIN:
        return skip(f"ROA too low: {roa:.2f}% (min {MIN_ROA_FIN}%)")

    traded_value = avg_volume * close_price
    if traded_value < MIN_TRADED_VALUE:
        return skip(f"Low liquidity: ₹{traded_value/1e7:.1f} Cr/day")

    anomaly = _anomaly_check(symbol, yoy_rev, yoy_profit)
    if anomaly:
        return skip(anomaly)

    # [VERSION: DAILY_BUILDER_PATCH_v1.8] Calculate promoter market cap using float and total outstanding shares
    float_shares = fv("float_shares_outstanding")
    total_shares = fv("total_shares_outstanding_fundamental")
    promoter_mcap = None
    if float_shares is not None and total_shares is not None and total_shares > 0 and market_cap is not None:
        non_float_shares = max(0, total_shares - float_shares)
        promoter_mcap = (non_float_shares / total_shares) * market_cap

    # ── JUNK-KILL GATE (Financial) — Non-negotiable hard blocks ─────────────────────
    if symbol in _BLACKLIST_SYMBOLS:
        return skip(f"JUNK BLOCKED (FIN): Promoter Blacklist / NSE Surveillance (ASM/GSM)")

    eps = fv("earnings_per_share_basic_ttm")
    roe = fv("return_on_equity_fy")
    
    # ── STRUCTURAL CATEGORIZATION & EXCEPTION RULES ──
    category = "NORMAL"
    is_turnaround_eps = (yoy_profit is not None and yoy_profit > 0) and (yoy_rev is not None and yoy_rev > 0)
    
    is_turnaround_candidate = (
        (roe is not None and roe < 5) or 
        (eps is not None and eps <= 0)
    )
    
    if is_turnaround_candidate:
        if not is_turnaround_eps:
            if eps is not None and eps <= 0:
                return skip(f"JUNK BLOCKED (FIN): Negative EPS {eps:.2f} (No turnaround exception)")
            if roe is not None and roe < 5:
                return skip(f"JUNK BLOCKED (FIN): Low ROE {roe:.1f}% (No turnaround exception)")
        else:
            category = "TURNAROUND"
            import logging
            logger = logging.getLogger("daily_builder")
            logger.info(f"TURNAROUND ADMITTED (FIN): {symbol} | ROE: {roe}% | EPS: {eps} | YoY Profit: {yoy_profit}% | YoY Rev: {yoy_rev}%")

    # [VERSION: DAILY_BUILDER_PATCH_v1.8] Enforce the non-negotiable MIN_PROMOTER_MCAP (₹500 Cr) gate
    if promoter_mcap is not None and promoter_mcap < MIN_PROMOTER_MCAP:
        return skip(f"JUNK BLOCKED (FIN): Promoter Market Cap ₹{promoter_mcap/1e7:.1f} Cr is below min ₹500 Cr")
        
    if forensic_flags >= 2:
        return skip(f"JUNK BLOCKED (FIN): Forensic Red Flags ({forensic_flags} detected)")

    # Both revenue AND profits collapsing = structural failure (Yes Bank, DHFL type)
    if yoy_rev < -20 and yoy_profit < -20:
        return skip(f"JUNK BLOCKED (FIN): Structural collapse Rev={yoy_rev:.1f}% Profit={yoy_profit:.1f}%")

    peg = None
    if pe is not None and pe > 0 and yoy_profit is not None and yoy_profit > 0:
        peg = pe / yoy_profit

    yoy_margin_expanding = (yoy_profit >= yoy_rev)

    fin_high_growth = (yoy_rev > FIN_HIGH_GROWTH_YOY and yoy_profit > FIN_HIGH_GROWTH_YOY and yoy_margin_expanding)
    fin_compounder = (yoy_rev > FIN_COMPOUNDER_YOY and yoy_profit > FIN_COMPOUNDER_YOY and roe >= 15 and roa >= 1.0)
    fin_mature_quality = (roe >= 15 and roa >= 1.0 and market_cap >= 50_000_000_000)
    fin_turnaround = (yoy_profit >= FIN_TURNAROUND_PROFIT and yoy_margin_expanding and yoy_rev >= -10.0 and roe >= 10 and roa >= 0.8)

    # NEW: Efficient lender
    efficient_lender = (roa >= 2.0 and roe >= 15.0 and market_cap >= 50_000_000_000)

    # NEW: Dividend Aristocrat
    div_val = div_yield if div_yield is not None else 0.0
    dividend_aristocrat = (div_val >= 3.0 and roe >= 15.0 and market_cap >= 50_000_000_000)

    # NEW: Institutional Accumulation
    # [VERSION: DAILY_BUILDER_PATCH_v1.6] Wire to module-level globals, not row (TV row lacks these columns)
    with _classify_lock:
        deliv_per = _DELIVERY_DATA.get(symbol, 0.0)
        inst_buyers = _INST_BUYS.get(symbol, [])
    inst_accumulation = (deliv_per >= 60.0 and len(inst_buyers) > 0 and roa >= 1.0)

    # ── DIAMOND HOLD (LONG TERM) LOGIC ──
    # [VERSION: DAILY_BUILDER_PATCH_v1.5] Aligned fin path to use lt_peg = pe / eps_5y with <= 2.0
    diamond_hold = False
    if rev_5y is not None and eps_5y is not None:
        fcf_ok = (fcf_margin is None) or (fcf_margin > 0)
        lt_peg = None
        if pe is not None and pe > 0 and eps_5y > 0:
            lt_peg = pe / eps_5y
        if (rev_5y >= 12.0
                and eps_5y >= 15.0
                and (lt_peg is None or lt_peg <= 2.0)
                and fcf_ok):
            diamond_hold = True

    # NEW: Market Share Gainer
    sector = str(row.get("sector", ""))
    sec_median = _SECTOR_MEDIANS.get(sector)
    market_share_gainer = False
    if sec_median is not None and sec_median > 0 and yoy_rev is not None:
        qoq_available = (qoq_profit is not None and qoq_rev is not None)
        margin_signal = yoy_margin_expanding if not qoq_available else (qoq_profit >= qoq_rev)
        market_share_gainer = (yoy_rev > (sec_median * 1.2) and margin_signal)

    # NEW: Early Stage Compounder
    MID_CAP_FLOOR = 50_000_000_000
    small_cap_compounder = (market_cap < MID_CAP_FLOOR and yoy_profit >= 25 and roe >= 18 and roa >= 1.5 and (rev_5y is None or rev_5y >= 15.0) and yoy_rev >= 20.0 and yoy_margin_expanding)

    if not any([fin_high_growth, fin_compounder, fin_mature_quality, fin_turnaround, diamond_hold, efficient_lender, dividend_aristocrat, inst_accumulation, market_share_gainer, small_cap_compounder]):
        return skip(f"No financial category — YoY NII={yoy_rev:.1f}%, YoY Profit={yoy_profit:.1f}%")

    cats = []
    if diamond_hold:       cats.append("Long Term Compounder")
    if dividend_aristocrat:cats.append("Dividend Aristocrat")
    if inst_accumulation:  cats.append("Inst Accumulation")
    if efficient_lender:   cats.append("Efficient Lender")
    if market_share_gainer:cats.append("Market Share Gainer")
    if small_cap_compounder:cats.append("Early Stage Compounder")
    if fin_high_growth:    cats.append("Fast Growing Financial")
    if fin_compounder:     cats.append("Top Bank/NBFC")
    if fin_mature_quality: cats.append("Blue Chip Financial")
    if fin_turnaround:     cats.append("Financial Recovery")
    if not cats:
        return skip(f"No categories assigned despite passing initial gates")

    # ── SCORING (Financial) ──────────────────────────────────────────────────
    # [VERSION: DAILY_BUILDER_PATCH_v1.3] Passed long-term params to _score_fin
    score = _score_fin(yoy_rev, yoy_profit, qoq_rev, qoq_profit, roe, roa,
                       yoy_margin_expanding, fin_mature_quality, fin_compounder,
                       dividend_aristocrat, sector,
                       diamond_hold=diamond_hold, rev_5y=rev_5y, 
                       eps_5y=eps_5y, fcf_margin=fcf_margin)
    if inst_accumulation: score += 5
    if insider_hold is not None and insider_hold > 0.50: score += 5

    return _build_row(
        symbol=symbol, cats=cats, path="Financial", row=row, close_price=close_price,
        market_cap=market_cap, roe=roe, opm=None, debt_equity=debt_equity, debt_missing=debt_missing,
        qoq_rev=qoq_rev, yoy_rev=yoy_rev, qoq_profit=qoq_profit, yoy_profit=yoy_profit, score=score, roa=roa, peg=peg, roce=roce, fcf_margin=fcf_margin,
        rev_5y=rev_5y, eps_5y=eps_5y, pe=pe, pb=pb
    )

